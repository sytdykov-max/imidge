type PageProps = {
  params: Promise<{ slug: string }>;
};

export async function generateMetadata({ params }: PageProps): Promise<Metadata> {
  const { slug } = await params;
  const page = PAGES[slug];

  if (!page) {
    return {
      title: "Страница не найдена",
    };
  }

  return {
    title: page.title,
    description: page.description,
    alternates: {
      canonical: `/${slug}`,
    },
  };
}

export default async function StaticInfoPage({ params }: PageProps) {
  const { slug } = await params;
  const page = PAGES[slug];

  if (!page) {
    notFound();
  }

  return (
    <div>
      <SiteHeader />

      <main id="main-content" className={`about-page info-page info-page-${slug}`} tabIndex={-1}>
        <section className="section about-shell">
          <div className="container about-layout">
            <aside className="about-sidebar">
              <p className="about-sidebar-title">О магазине⌚</p>
              <nav aria-label="Разделы о магазине">
                <ul className="about-sidebar-list">
                  {ABOUT_MENU.map((item) => (
                    <li key={item.href}>
                      <a href={item.href} aria-current={item.href === `/${slug}` ? "page" : undefined}>
                        {item.label}
                      </a>
                    </li>
                  ))}
                </ul>
              </nav>
            </aside>

            <article className="about-content">
              <p className="about-kicker">{page.kicker}</p>
              <h1 className="about-title">{page.title}</h1>

              {page.lead ? <p className="about-lead">{page.lead}</p> : null}

              {page.sections.map((section) => (
                <section className="info-block" key={section.title ?? section.paragraphs?.[0] ?? "section"}>
                  {section.title ? <h2 className="section-title about-section-title">{section.title}</h2> : null}
                  {section.paragraphs?.map((paragraph) => <p key={paragraph}>{paragraph}</p>)}
                  {section.bullets?.length ? (
                    <ul>
                      {section.bullets.map((bullet) => (
                        <li key={bullet}>{bullet}</li>
                      ))}
                    </ul>
                  ) : null}
                </section>
              ))}
            </article>
          </div>
        </section>
      </main>

      <SiteFooter />
    </div>
  );
}
